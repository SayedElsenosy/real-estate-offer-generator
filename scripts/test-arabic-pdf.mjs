import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PDFDocument } from "pdf-lib";
import fontkit from "@pdf-lib/fontkit";
import { drawArabicText } from "arabic-bidi-shaper/pdf-lib";

const fontBytes=readFileSync("node_modules/@fontsource/ibm-plex-sans-arabic/files/ibm-plex-sans-arabic-arabic-400-normal.woff");
const pdf=await PDFDocument.create();
pdf.registerFontkit(fontkit);
const font=await pdf.embedFont(fontBytes,{subset:true});
const page=pdf.addPage([595.28,841.89]);
drawArabicText(page,"عرض سعر عقاري",{x:540,y:720,font,size:20,align:"right"});
drawArabicText(page,"جدول الأقساط ووديعة الصيانة",{x:540,y:670,font,size:15,align:"right"});
drawArabicText(page,"المبلغ 1,234.50 جنيه",{x:540,y:630,font,size:15,align:"right"});
const result=await pdf.save({useObjectStreams:false});
assert.ok(result.byteLength>2500,"Arabic glyph font must be embedded");
assert.equal(new TextDecoder().decode(result.slice(0,5)),"%PDF-");
const source=readFileSync("src/components/Studio.tsx","utf8");
assert.ok(source.includes('useState<"ar"|"en">("ar")'),"Arabic must default for PDF exports");
assert.ok(source.includes('language:offerLanguage'),"Offer form must submit requested language");
const arPdf=readFileSync("src/lib/arabic-pdf.ts","utf8");
const enPdf=readFileSync("src/lib/workers-pdf.ts","utf8");
const engine=readFileSync("src/lib/payment.ts","utf8");
const studio=readFileSync("src/components/Studio.tsx","utf8");
assert.ok(arPdf.includes('payment.due||"-"'),"Arabic PDF must display no date on the maintenance row");
assert.ok(enPdf.includes('entry.due||"-"'),"English PDF must display no date on the maintenance row");
assert.ok(!arPdf.includes("تاريخ وديعة الصيانة"),"Arabic PDF must not ask for a maintenance due date");
assert.ok(!enPdf.includes('"Maintenance due"'),"English PDF must not include maintenance due date");
assert.ok(engine.indexOf('rows.sort(')<engine.indexOf('rows.push({number:null,type:"MAINTENANCE"'),"Maintenance must be appended after sorted installments");
assert.ok(!studio.includes('setMaintenanceDueDate'),"Studio must not ask for maintenance date");
console.log("PASS: self-hosted Arabic font, both PDF languages and final undated maintenance row");
