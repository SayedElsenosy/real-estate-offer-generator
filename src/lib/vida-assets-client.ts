import type { VidaBrochureMatch } from "@/lib/vida-brochure";

export type VidaBrochureImages = {
  building: string;
  floor: string;
  unit: string | null;
};
let assetArchive:Promise<Uint8Array>|null=null;
async function loadArchive():Promise<Uint8Array>{
  if(!assetArchive)assetArchive=(async()=>{
    const response=await fetch("/api/vida/assets",{
      credentials:"same-origin",cache:"no-store"
    });
    if(!response.ok)throw Error("Vida original brochure assets are unavailable (HTTP "+response.status+").");
    const bytes=new Uint8Array(await response.arrayBuffer());
    if(bytes.length<1000||bytes.length>7_000_000)throw Error("Invalid Vida brochure archive.");
    return bytes;
  })().catch(err=>{assetArchive=null;throw err;});
  return assetArchive;
}

/**
 * Read only the required source-page JPEGs from the validated original-source
 * ZIP. The crop itself was produced offline from the supplied brochure.
 * No floorplan is drawn, traced, or generated by this client.
 */
async function readZipEntry(zip:Uint8Array,entry:string):Promise<string>{
  const view=new DataView(zip.buffer,zip.byteOffset,zip.byteLength);
  let i=0;
  while(i+30<=zip.byteLength&&view.getUint32(i,true)===0x04034b50){
    const method=view.getUint16(i+8,true);
    const compressedSize=view.getUint32(i+18,true);
    const nameSize=view.getUint16(i+26,true);
    const extraSize=view.getUint16(i+28,true);
    const name=new TextDecoder().decode(zip.subarray(i+30,i+30+nameSize));
    const start=i+30+nameSize+extraSize;
    if(start+compressedSize>zip.byteLength)throw Error("Vida brochure archive is truncated.");
    if(name===entry){
      if(compressedSize>2_000_000)throw Error("Vida brochure entry exceeds permitted size.");
      const bytes=zip.slice(start,start+compressedSize);
      if(method===0)return new TextDecoder().decode(bytes);
      if(method!==8)throw Error("Vida brochure compression method is unsupported.");
      // Native browser ZIP deflate decoder, avoids loading a large PDF or
      // adding expensive PDF rendering to Cloudflare's 10ms CPU requests.
      const stream=new Blob([bytes]).stream().pipeThrough(new DecompressionStream("deflate-raw"));
      const raw=await new Response(stream).arrayBuffer();
      if(raw.byteLength>3_000_000)throw Error("Vida brochure entry is too large.");
      return new TextDecoder().decode(raw);
    }
    i=start+compressedSize;
  }
  throw Error("Vida brochure source page is missing: "+entry);
}
function imageFromEntry(entry:unknown,description:string):string{
  if(typeof entry!=="object"||!entry)throw Error("Invalid "+description);
  const o=entry as {jpeg?:unknown};
  if(typeof o.jpeg!=="string"||!/^[a-z0-9+/]+={0,2}$/i.test(o.jpeg)||o.jpeg.length>1_400_000)
    throw Error("Invalid original brochure JPEG: "+description);
  return "data:image/jpeg;base64,"+o.jpeg;
}
export async function loadVidaBrochureImages(match:VidaBrochureMatch):Promise<VidaBrochureImages>{
  const archive=await loadArchive();
  const [masterString,groupString]=await Promise.all([
    readZipEntry(archive,"master.json"),
    readZipEntry(archive,match.assetGroup+".json")
  ]);
  const master=JSON.parse(masterString) as {version:number;buildings:Record<string,unknown>};
  const group=JSON.parse(groupString) as {version:number;group:string;phase:number;pages:Record<string,unknown>};
  if(master.version!==1||group.version!==1||group.group!==match.assetGroup||group.phase!==match.phase)
    throw Error("Vida brochure source does not match the chosen project.");
  const building=imageFromEntry(master.buildings[String(match.building)],"masterplan building");
  const floor=imageFromEntry(group.pages[String(match.floorPage)],"floorplan");
  const unit=match.unitPage===null?null:imageFromEntry(group.pages[String(match.unitPage)],"unit plan");
  return {building,floor,unit};
}
